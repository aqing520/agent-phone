#!/usr/bin/env python3
"""Render the Agent Phone brand mark across Flutter and the native launchers.

Run `python3 tool/make_brand_mark.py` from app/. Requires Pillow.
The 108-unit launcher grid has a 72-unit visible tile. The default icon uses
agent-phone.png, supplied at the repository root. Alternate icons and the
monochrome mark share SVG geometry with the Flutter brand mark.
"""
from pathlib import Path
import xml.etree.ElementTree as ET

from PIL import Image, ImageChops, ImageDraw

APP = Path(__file__).resolve().parents[1]
BRAND = APP / 'assets/brand'
ANDROID = APP / 'android/app/src/main/res'
IOS = APP / 'ios/Runner/Assets.xcassets'
OHOS = APP / 'ohos'
OHOS_APP = OHOS / 'AppScope/resources/base/media'
OHOS_ENTRY = OHOS / 'entry/src/main/resources/base/media'
NS = '{http://schemas.android.com/apk/res/android}'
SVG_NS = 'http://www.w3.org/2000/svg'
COLORS = {'mist': '#FFFFFF', 'night': '#FFFFFF', 'frost': '#6555BB', 'ink': '#F5F7FB'}
SOURCE = BRAND / 'glyph-mono.svg'


def svg(view, elements):
    return f'<svg xmlns="{SVG_NS}" viewBox="{view}">{elements}</svg>\n'


def rect(x, y, side, radius, fill):
    return f'<rect x="{x}" y="{y}" width="{side}" height="{side}" rx="{radius}" fill="{fill}"/>'


def marks(squares, fill):
    return ''.join(rect(x, y, side, r, fill) for x, y, side, r in squares)


def gradient(icon):
    suffix = '' if icon == 'mist' else f'_{icon}'
    path = ANDROID / f'drawable/ic_launcher{suffix}_background.xml'
    node = ET.parse(path).getroot().find('.//gradient')
    start, end = ('#' + item.attrib[NS + 'color'][3:] for item in node.findall('item'))
    x1, y1, x2, y2 = (node.attrib[NS + key] for key in ('startX', 'startY', 'endX', 'endY'))
    return (x1, y1, x2, y2), (start, end)


def svg_gradient(points, colors):
    x1, y1, x2, y2 = points
    start, end = colors
    return (f'<defs><linearGradient id="tile-bg" gradientUnits="userSpaceOnUse" '
            f'x1="{x1}" y1="{y1}" x2="{x2}" y2="{y2}">'
            f'<stop offset="0" stop-color="{start}"/><stop offset="1" stop-color="{end}"/>'
            '</linearGradient></defs>')


def background(size, view, points, colors):
    # Project each output coordinate onto the gradient axis using an affine lookup.
    origin, span = view
    x1, y1, x2, y2 = map(float, points)
    dx, dy = x2 - x1, y2 - y1
    scale = 255 / (dx * dx + dy * dy)
    offset = scale * ((origin - x1) * dx + (origin - y1) * dy)
    ramp = Image.new('L', (768, 1))
    ramp.paste(Image.linear_gradient('L').transpose(Image.Transpose.TRANSPOSE).crop((0, 0, 256, 1)), (256, 0))
    ramp.paste(255, (512, 0, 768, 1))
    tone = ramp.transform((size, size), Image.Transform.AFFINE,
                          (scale * dx * span / size, scale * dy * span / size, offset + 256, 0, 0, 0),
                          Image.Resampling.BILINEAR)
    # The padded ramp clamps out-of-range coordinates to its end colors.
    return Image.composite(Image.new('RGB', tone.size, colors[1]), Image.new('RGB', tone.size, colors[0]), tone)


def geometry(size, view, squares, fill):
    origin, span = view
    scale = size / span
    fg = Image.new('RGBA', (size, size))
    draw = ImageDraw.Draw(fg)
    for x, y, side, r in squares:
        left, top = (x - origin) * scale, (y - origin) * scale
        draw.rounded_rectangle((left, top, left + side * scale - 1, top + side * scale - 1),
                               radius=r * scale, fill=fill)
    return fg


def mask(image, style, inset=0):
    shape = Image.new('L', image.size)
    side, _ = image.size
    draw = ImageDraw.Draw(shape)
    box = (inset, inset, side - inset - 1, side - inset - 1)
    if style == 'circle':
        draw.ellipse(box, fill=255)
    else:
        draw.rounded_rectangle(box, (side - 2 * inset) * 15 / 72, fill=255)
    image.putalpha(ImageChops.multiply(image.getchannel('A'), shape))
    return image


def save(image, out, size, *, opaque=False):
    image.resize((size, size), Image.Resampling.LANCZOS).convert('RGB' if opaque else 'RGBA').save(out, optimize=True)


def dart(squares, box):
    shape = '\n'.join(f'    ..addRRect(RRect.fromRectAndRadius(Rect.fromLTWH({x}, {y}, {s}, {s}), Radius.circular({r})))'
                      for x, y, s, r in squares)
    x, y, w, h = box
    return f'''// GENERATED by tool/make_brand_mark.py from assets/brand/glyph-mono.svg.
// Do not edit; change the master and rerun the tool.

// dart format off
import 'dart:ui' show Offset, Path, RRect, Radius, Rect;

abstract final class BrandGlyph {{
  static const box = Rect.fromLTWH({x}, {y}, {w}, {h});
  static const aspect = {w / h};
  static const centroid = Offset({x + w / 2}, {y + h / 2});
  static const tileBox = Rect.fromLTWH(18, 18, 72, 72);
  static final Path glyph = Path()
{shape};
  static final Path tile = Path()
    ..addRRect(RRect.fromRectAndRadius(tileBox, const Radius.circular(15)));
}}
'''


def monochrome(squares, size=108):
    # Arc commands match the circular corners of the SVG and Flutter RRect.
    paths = []
    for x, y, side, r in squares:
        right, bottom = x + side, y + side
        arc = f'A{r},{r} 0 0 1'
        paths.append(f'M{x + r},{y} H{right - r} {arc} {right},{y + r} '
                     f'V{bottom - r} {arc} {right - r},{bottom} H{x + r} '
                     f'{arc} {x},{bottom - r} V{y + r} {arc} {x + r},{y} Z')
    return ('<?xml version="1.0" encoding="utf-8"?>\n'
            '<!-- Generated by tool/make_brand_mark.py. -->\n'
            '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
            f'    android:width="{size}dp" android:height="{size}dp"\n'
            f'    android:viewportWidth="{size}" android:viewportHeight="{size}">\n'
            f'    <path android:fillColor="#FFFFFFFF" android:pathData="{" ".join(paths)}" />\n'
            '</vector>\n')


def default_portrait():
    path = APP.parents[1] / 'agent-phone.png'
    with Image.open(path) as source:
        source = source.convert('RGB')
    # The visible 576 px crop is centered around (680, 345). Extend the
    # top edge in the invisible overscan instead of cutting it off mid-motion.
    x, y, side = 248, -87, 864
    layer = Image.new('RGB', (side, side))
    layer.paste(source.crop((x, 0, x + side, y + side)), (0, -y))
    layer.paste(source.crop((x, 0, x + side, 1)).resize((side, -y)), (0, 0))
    return layer


def main():
    master = ET.parse(SOURCE).getroot()
    view = master.attrib['viewBox']
    squares = [tuple(float(el.attrib[key]) for key in ('x', 'y', 'width', 'rx'))
               for el in master.iter(f'{{{SVG_NS}}}rect')]
    (APP / 'lib/ui/shell/brand_glyph.g.dart').write_text(dart(squares, tuple(map(float, view.split()))))
    (ANDROID / 'drawable/ic_launcher_monochrome.xml').write_text(monochrome(squares))
    x0, y0, width, _ = map(float, view.split())
    scale = 22 / width
    notification = [tuple(round(value, 4) for value in (1 + (x - x0) * scale, 1 + (y - y0) * scale,
                                                       side * scale, r * scale))
                    for x, y, side, r in squares]
    (ANDROID / 'drawable/ic_stat_dsh.xml').write_text(monochrome(notification, 24))
    (BRAND / 'glyph-light.svg').write_text(svg(view, marks(squares, COLORS['frost'])))
    (BRAND / 'glyph-dark.svg').write_text(svg(view, marks(squares, COLORS['mist'])))
    layer_size, tile_size = 1536, 1024
    portrait = default_portrait().resize((layer_size, layer_size), Image.Resampling.LANCZOS)
    for icon, fill in COLORS.items():
        points, colors = gradient(icon)
        bg = background(layer_size, (0, 108), points, colors)
        fg = portrait.convert('RGBA') if icon == 'mist' else geometry(layer_size, (0, 108), squares, fill)
        composite = Image.alpha_composite(bg.convert('RGBA'), fg)
        inset = (layer_size - tile_size) // 2
        tile = composite.crop((inset, inset, inset + tile_size, inset + tile_size))
        rounded = mask(tile.copy(), 'rounded')
        circular = mask(tile.copy(), 'circle')
        suffix = '' if icon == 'mist' else f'_{icon}'
        for density, side in [('mdpi', 48), ('hdpi', 72), ('xhdpi', 96), ('xxhdpi', 144), ('xxxhdpi', 192)]:
            stem = ANDROID / f'mipmap-{density}/ic_launcher{suffix}'
            save(rounded, stem.with_suffix('.png'), side)
            save(circular, stem.with_name(stem.name + '_round.png'), side)
            save(fg, stem.with_name(stem.name + '_foreground.png'), side * 108 // 48)
        ios_name = 'AppIcon' + ('' if icon == 'mist' else icon.title())
        save(tile, IOS / f'{ios_name}.appiconset/{ios_name}-1024.png', 1024, opaque=True)
        launch_name = 'LaunchIcon' + icon.title()
        save(tile, IOS / f'{launch_name}.imageset/{launch_name}.png', 512, opaque=True)
        layer_prefix = '' if icon == 'mist' else icon + '_'
        for media in (OHOS_APP, OHOS_ENTRY) if icon == 'mist' else (OHOS_APP,):
            save(bg, media / f'{layer_prefix}background.png', 1024, opaque=True)
            save(fg, media / f'{layer_prefix}foreground.png', 1024)
        if icon == 'mist':
            (BRAND / 'tile.svg').write_text(svg('18 18 72 72', svg_gradient(points, colors)
                                                + rect(18, 18, 72, 15, 'url(#tile-bg)') + marks(squares, fill)))
            save(tile, BRAND / 'launcher-preview.png', 256, opaque=True)
            save(rounded, OHOS_ENTRY / 'icon.png', 192)
            save(mask(composite, 'rounded', inset), OHOS_ENTRY / 'start_icon.png', 648)


if __name__ == '__main__':
    main()
